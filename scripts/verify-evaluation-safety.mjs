import assert from 'node:assert/strict';
import { createEvaluationCircuit, advanceEvaluationCircuit, estimateEvaluationCost, summarizeEvaluationCost } from '../base44/shared/evaluationSafety.js';
import { evaluateResponse } from '../base44/shared/modelRouter.js';
let state=createEvaluationCircuit(0);
for(let i=0;i<16;i++)state=advanceEvaluationCircuit(state,'CALL',1);
assert.equal(state.status,'ACTIVE');
state=advanceEvaluationCircuit(state,'CALL',1);
assert.equal(state.status,'FROZEN');
assert.deepEqual(advanceEvaluationCircuit(state,'CHECK',2),state);
assert.equal(advanceEvaluationCircuit(createEvaluationCircuit(0),'CHECK',120000).status,'FROZEN');
state=advanceEvaluationCircuit(createEvaluationCircuit(0),'ERROR',1);
assert.equal(state.status,'ACTIVE');
assert.equal(advanceEvaluationCircuit(state,'ERROR',2).status,'FROZEN');
assert.equal(advanceEvaluationCircuit(createEvaluationCircuit(0),'POLICY_DENIAL',1).status,'FROZEN');
assert.equal(estimateEvaluationCost('1234','12345678',1,3),7/1000000);
assert.equal(estimateEvaluationCost('x','y',undefined,3),null);
assert.equal(estimateEvaluationCost('x','y',-1,3),null);
assert.equal(summarizeEvaluationCost([{pass:true,estimated_cost_usd:.1},{pass:false,estimated_cost_usd:.2}]).successful_tasks,1);
assert.ok(Math.abs(summarizeEvaluationCost([{pass:true,estimated_cost_usd:.1},{pass:false,estimated_cost_usd:.2}]).cost_per_successful_task_usd-.3)<1e-12);
assert.equal(summarizeEvaluationCost([{pass:false,estimated_cost_usd:.2}]).cost_per_successful_task_usd,null);
assert.equal(summarizeEvaluationCost([{pass:true,estimated_cost_usd:null}]).cost_status,'UNKNOWN');
assert.equal(summarizeEvaluationCost([{pass:false,error:'timeout',estimated_cost_usd:0}]).estimated_cost_usd,null);
assert.equal(evaluateResponse({expect_json:true},'not JSON').pass,false);
assert.equal(evaluateResponse({forbidden_terms:['done']},'done').pass,false);
assert.equal(evaluateResponse({required_terms:['approval']},'okay').pass,false);
assert.equal(evaluateResponse({expect_json:true},'{"ok":true}').pass,true);
console.log('Evaluation safety: 18 regression assertions passed');
